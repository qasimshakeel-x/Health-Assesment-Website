"""PDF Report routes — async generation with status polling."""
import os
import asyncio
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException, BackgroundTasks
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session
from backend.app.models.database import get_db, SessionLocal, User, UserProfile, PredictionResult, ReportLog
from backend.app.middleware.auth import get_current_user

router = APIRouter()

# Absolute PDF dir — cwd-relative path pe download aur generate alag jagah likh rahe the (BUG-2 fix)
PDF_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "pdfs")


def _update_report(report_id: int, **fields):
    """Background task ke liye apna DB session (request session tab tak close ho chuka hota hai)."""
    db = SessionLocal()
    try:
        report = db.query(ReportLog).filter(ReportLog.id == report_id).first()
        if report:
            for key, value in fields.items():
                setattr(report, key, value)
            db.commit()
    finally:
        db.close()


def generate_pdf_report(report_id: int, user_profile_id: int, prediction_id: int):
    """Generate a clinical-grade PDF report using ReportLab.

    Spec (12-INTEGRATION.md §6) ke mutabik: cover + health profile + 16-disease risk
    table (WS-6) + scores + SHAP/chat sections Round 2 mein add honge.
    """
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.units import inch
        from reportlab.lib import colors
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    except ImportError:
        # ReportLab missing → status failed mark karo, warna poll hamesha "processing" rahega
        _update_report(report_id, status="failed", generated_at=datetime.utcnow())
        return

    try:
        os.makedirs(PDF_DIR, exist_ok=True)
        pdf_path = os.path.join(PDF_DIR, f"report_{user_profile_id}_{prediction_id}.pdf")

        # Background task → apna DB session (request session tab tak band ho chuka hai)
        db = SessionLocal()
        try:
            prediction = db.query(PredictionResult).filter(PredictionResult.id == prediction_id).first()
            profile = db.query(UserProfile).filter(UserProfile.id == user_profile_id).first()
            rows = list(getattr(prediction, "disease_risk_results", None) or []) if prediction else []
        finally:
            db.close()

        doc = SimpleDocTemplate(pdf_path, pagesize=A4)
        styles = getSampleStyleSheet()
        # getSampleStyleSheet() mein "Warning" style hota hi nahi → KeyError se poora task crash hota tha
        styles.add(ParagraphStyle(name="Warning", parent=styles["Normal"], textColor="#C62828",
                                  fontSize=10, leading=14, spaceBefore=6, spaceAfter=6))
        elements = []

        # Cover page
        elements.append(Paragraph("AI & ML Longevity Intelligence Platform", styles["Title"]))
        elements.append(Spacer(1, 0.5 * inch))
        elements.append(Paragraph("Your Personalized Health Report", styles["Heading2"]))
        elements.append(Spacer(1, 0.3 * inch))
        elements.append(Paragraph(
            "DISCLAIMER: This report is generated by AI & ML and is not a medical diagnosis. "
            "Consult a qualified doctor.", styles["Warning"]))
        elements.append(Spacer(1, 0.5 * inch))
        elements.append(Paragraph("Generated by AI & ML Longevity Intelligence Platform", styles["Normal"]))

        # ── Health Profile ──
        if profile:
            elements.append(Spacer(1, 0.4 * inch))
            elements.append(Paragraph("Health Profile", styles["Heading2"]))
            gender = {0: "Female", 1: "Male"}.get(profile.gender, "—")
            prof_data = [
                ["Age", str(profile.age or "—"), "Gender", gender],
                ["Height (cm)", str(profile.height or "—"), "Weight (kg)", str(profile.weight or "—")],
                ["BMI", f"{profile.bmi:.1f}" if profile.bmi else "—",
                 "Sleep (hrs)", str(profile.sleep_hours or "—")],
                ["Exercise", str(profile.exercise_level or "—"),
                 "Smoking", "Yes" if profile.smoking else "No"],
            ]
            t = Table(prof_data, hAlign="LEFT")
            t.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 9),
                                   ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
            elements.append(t)

            if prediction:
                elements.append(Spacer(1, 0.2 * inch))
                scores = [
                    f"Biological Age: {prediction.biological_age:.1f} yrs" if prediction.biological_age else "",
                    f"Longevity Score: {prediction.longevity_score:.0f}/100" if prediction.longevity_score is not None else "",
                    f"Depression Level: {prediction.depression_level}" if prediction.depression_level else "",
                ]
                elements.append(Paragraph(" &nbsp;|&nbsp; ".join(s for s in scores if s), styles["Normal"]))

        # ── 16-Disease Risk Table (WS-6) ──
        if rows:
            from ml.models.registry import DISEASE_REGISTRY
            order = {k: i for i, k in enumerate(DISEASE_REGISTRY.keys())}
            rows.sort(key=lambda r: order.get(r.disease_key, 999))
            elements.append(Spacer(1, 0.3 * inch))
            elements.append(Paragraph("Disease Risk Summary", styles["Heading2"]))

            data = [["Disease", "Category", "Risk", "Level"]]
            cancer_disclaimer = False
            for r in rows:
                cfg = DISEASE_REGISTRY.get(r.disease_key)
                label = cfg.label if cfg else r.disease_key.replace("_", " ").title()
                cat = r.category.replace("_", " ").title() if r.category else "—"
                data.append([label, cat, f"{float(r.risk_percent or 0):.1f}%", r.risk_label or "—"])
                if r.category == "cancer_screening":
                    cancer_disclaimer = True

            t = Table(data, hAlign="LEFT", repeatRows=1)
            t.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#263238")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#90A4AE")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#ECEFF1")]),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
            ]))
            elements.append(t)
            if cancer_disclaimer:
                elements.append(Spacer(1, 0.15 * inch))
                elements.append(Paragraph(
                    "Cancer estimates are population-level risk estimates, not diagnostic tools.",
                    styles["Warning"]))

        doc.build(elements)

        # Success → poll endpoint (status/download) ab kaam karega
        file_size = os.path.getsize(pdf_path) / 1024
        _update_report(report_id, status="success", pdf_path=pdf_path,
                       file_size_kb=round(file_size, 2), generated_at=datetime.utcnow())
    except Exception as exc:
        # Unhandled exception silently 202→pending chhod deta tha (audit BUG-2)
        _update_report(report_id, status="failed", generated_at=datetime.utcnow())
        print(f"[reports] PDF generation failed for report_id={report_id}: {exc}")


@router.post("/{user_id}/generate", status_code=202)
def generate_report(
    user_id: int,
    background_tasks: BackgroundTasks,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Trigger async PDF generation. Returns 202 with report ID."""
    # Get latest prediction
    prediction = (
        db.query(PredictionResult)
        .join(UserProfile)
        .filter(UserProfile.user_id == user_id)
        .order_by(PredictionResult.created_at.desc())
        .first()
    )
    if not prediction:
        raise HTTPException(status_code=404, detail="No prediction found")

    profile = db.query(UserProfile).filter(UserProfile.user_id == user_id).order_by(UserProfile.created_at.desc()).first()

    # Create report log entry
    report = ReportLog(user_profile_id=profile.id, status="processing")
    db.add(report)
    db.commit()
    db.refresh(report)

    # Generate in background (report_id pass taaki status update ho sake)
    background_tasks.add_task(generate_pdf_report, report.id, profile.id, prediction.id)

    return {"report_id": report.id, "status": "processing", "message": "PDF generation started"}


@router.get("/{user_id}/list")
def list_reports(
    user_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """List a user's generated reports (Reports page — newest first)."""
    rows = (
        db.query(ReportLog)
        .join(UserProfile, ReportLog.user_profile_id == UserProfile.id)
        .filter(UserProfile.user_id == user_id)
        .order_by(ReportLog.generated_at.desc())
        .limit(50)
        .all()
    )
    return {
        "reports": [
            {
                "id": r.id,
                "status": r.status,
                "generated_at": str(r.generated_at) if r.generated_at else None,
                "file_size_kb": r.file_size_kb,
                "downloadable": bool(r.status == "success" and r.pdf_path and os.path.exists(r.pdf_path)),
            }
            for r in rows
        ]
    }


@router.get("/{report_id}/status")
def get_report_status(
    report_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Poll PDF generation status."""
    report = db.query(ReportLog).filter(ReportLog.id == report_id).first()
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")

    return {
        "report_id": report.id,
        "status": report.status,
        "generated_at": report.generated_at,
        "file_size_kb": report.file_size_kb
    }


@router.get("/{report_id}/download")
def download_report(
    report_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    """Download finished PDF."""
    report = db.query(ReportLog).filter(ReportLog.id == report_id).first()
    if not report:
        raise HTTPException(status_code=404, detail="Report not found")
    if report.status != "success" or not report.pdf_path or not os.path.exists(report.pdf_path):
        raise HTTPException(status_code=404, detail="PDF not ready")

    return FileResponse(
        report.pdf_path,
        media_type="application/pdf",
        filename=f"health_report_{report.id}.pdf"
    )
